#!/usr/bin/env python3
"""Source of truth: assets/collision-world.json. C, Rust and browser must agree."""
import json
from pathlib import Path
r=Path(__file__).resolve().parents[1]
w=json.loads((r/'assets/collision-world.json').read_text(encoding='utf8'))
def cf(v):return f'{float(v):.4f}f'
def rf(v):return f'{float(v):.4f}'
b=w['bounds']
h=f'''/* Generated by tools/generate_colliders.py from assets/collision-world.json */
#define PLAYER_RADIUS {cf(w['playerRadius'])}
#define WORLD_MIN_X {cf(b['minX'])}
#define WORLD_MAX_X {cf(b['maxX'])}
#define WORLD_MIN_Z {cf(b['minZ'])}
#define WORLD_MAX_Z {cf(b['maxZ'])}
static const float houses[{len(w['houses'])}][4] = {{
'''
h+=''.join('  {'+','.join(cf(v[k]) for k in ('x','z','halfX','halfZ'))+'},\n' for v in w['houses'])
h += '};\n' + f'#define HOUSE_COUNT {len(w["houses"])}\n' + 'static const float fountain[3] = {' + ','.join(cf(w['fountain'][k]) for k in ('x','z','radius')) + '};\n' 
h+=f'static const float trees[{len(w["trees"])}][3] = {{\n'
h+=''.join('  {'+','.join(cf(v[k]) for k in ('x','z','radius'))+'},\n' for v in w['trees'])
h+=f'}};\n#define TREE_COUNT {len(w["trees"])}\n'
e=w['elevation'];d=e['deck'];a=e['access']
h+='/* Walkable elevated deck and ramp/stair access: all values from shared world JSON. */\n'
for name,value in [
  ('DECK_X',d['x']),('DECK_HALF_X',d['halfX']),('DECK_Z_MIN',d['zMin']),('DECK_Z_MAX',d['zMax']),('DECK_HEIGHT',d['height']),
  ('ACCESS_X',a['x']),('ACCESS_HALF_X',a['halfX']),('ACCESS_Z_MIN',a['zMin']),('ACCESS_Z_MAX',a['zMax']),
  ('STAIRS_FROM_X',a['stairsFromX']),('MAX_STEP_UP',e['maxStepUp']),('WORLD_GRAVITY',e['gravity']),('JUMP_VELOCITY',e['jumpVelocity'])
]:h+=f'#define {name} {cf(value)}\n'
h+=f'#define STAIR_STEPS {int(a["steps"])}\n'
# Southern descent out of original village (the return route must also be walkable).
sa=w['southAccess']
for name,value in [('SOUTH_ACCESS_X',sa['x']),('SOUTH_ACCESS_HALF_X',sa['halfX']),('SOUTH_ACCESS_Z_MIN',sa['zMin']),('SOUTH_ACCESS_Z_MAX',sa['zMax'])]:h+=f'#define {name} {cf(value)}\n'

u=w['upperVillage'];ud=u['deck'];ua=u['access']
h+='/* Additional northern village terrace, walkable from its front stairs/ramp. */\n'
for name,value in [('UPPER_DECK_X',ud['x']),('UPPER_DECK_HALF_X',ud['halfX']),('UPPER_DECK_Z_MIN',ud['zMin']),('UPPER_DECK_Z_MAX',ud['zMax']),('UPPER_DECK_HEIGHT',ud['height']),('UPPER_ACCESS_X',ua['x']),('UPPER_ACCESS_HALF_X',ua['halfX']),('UPPER_ACCESS_Z_MIN',ua['zMin']),('UPPER_ACCESS_Z_MAX',ua['zMax']),('UPPER_STAIRS_FROM_X',ua['stairsFromX'])]:h+=f'#define {name} {cf(value)}\n'
h+=f'#define UPPER_STAIR_STEPS {int(ua["steps"])}\n'
# Both existing and northern access ways need physical side faces.
# Derive the footprints from access dimensions so C, Rust and Three.js agree.
side=w['accessSideWalls']
walls=[]
for access in (w['elevation']['access'],w['upperVillage']['access'],w['southAccess']):
    center_z=(access['zMin']+access['zMax'])/2
    hz=(access['zMax']-access['zMin'])/2+side['endCap']
    for sign in (-1,1):
        walls.append((access['x']+sign*access['halfX'],center_z,side['halfThickness'],hz))
h+='/* Solid side edges of both sloped/stair access lanes. */\n'
h+=f'#define STAIR_WALL_COUNT {len(walls)}\n'
h+=f'static const float stair_walls[{len(walls)}][4] = {{\n'
h+=''.join('  {'+','.join(cf(c) for c in wall)+'},\n' for wall in walls)
h+='};\n'

(r/'src/world.generated.h').write_text(h,encoding='utf8')
rs='// Generated by tools/generate_colliders.py from assets/collision-world.json\n'
rs+=f'const PLAYER_RADIUS: f32 = {rf(w["playerRadius"])};\n'
for name,key in [('WORLD_MIN_X','minX'),('WORLD_MAX_X','maxX'),('WORLD_MIN_Z','minZ'),('WORLD_MAX_Z','maxZ')]:rs+=f'const {name}: f32 = {rf(b[key])};\n'
rs+=f'const HOUSES: [(f32,f32,f32,f32);{len(w["houses"])}] = [\n'
rs+=''.join('  ('+','.join(rf(v[k]) for k in ('x','z','halfX','halfZ'))+'),\n' for v in w['houses'])
rs+='];\nconst FOUNTAIN:(f32,f32,f32) = ('+','.join(rf(w['fountain'][k]) for k in ('x','z','radius'))+');\n'
rs+=f'const TREES: [(f32,f32,f32);{len(w["trees"])}] = [\n'
rs+=''.join('  ('+','.join(rf(v[k]) for k in ('x','z','radius'))+'),\n' for v in w['trees'])
rs+='];\n'
for name,value in [
  ('DECK_X',d['x']),('DECK_HALF_X',d['halfX']),('DECK_Z_MIN',d['zMin']),('DECK_Z_MAX',d['zMax']),('DECK_HEIGHT',d['height']),
  ('ACCESS_X',a['x']),('ACCESS_HALF_X',a['halfX']),('ACCESS_Z_MIN',a['zMin']),('ACCESS_Z_MAX',a['zMax']),
  ('STAIRS_FROM_X',a['stairsFromX']),('MAX_STEP_UP',e['maxStepUp']),('WORLD_GRAVITY',e['gravity']),('JUMP_VELOCITY',e['jumpVelocity'])
]:rs+=f'const {name}: f32 = {rf(value)};\n'
rs+=f'const STAIR_STEPS: i32 = {int(a["steps"])};\n'
for name,value in [('SOUTH_ACCESS_X',sa['x']),('SOUTH_ACCESS_HALF_X',sa['halfX']),('SOUTH_ACCESS_Z_MIN',sa['zMin']),('SOUTH_ACCESS_Z_MAX',sa['zMax'])]:rs+=f'const {name}: f32 = {rf(value)};\n'

for name,value in [('UPPER_DECK_X',ud['x']),('UPPER_DECK_HALF_X',ud['halfX']),('UPPER_DECK_Z_MIN',ud['zMin']),('UPPER_DECK_Z_MAX',ud['zMax']),('UPPER_DECK_HEIGHT',ud['height']),('UPPER_ACCESS_X',ua['x']),('UPPER_ACCESS_HALF_X',ua['halfX']),('UPPER_ACCESS_Z_MIN',ua['zMin']),('UPPER_ACCESS_Z_MAX',ua['zMax']),('UPPER_STAIRS_FROM_X',ua['stairsFromX'])]:rs+=f'const {name}: f32 = {rf(value)};\n'
rs+=f'const UPPER_STAIR_STEPS: i32 = {int(ua["steps"])};\n'
rs+=f'const STAIR_WALLS: [(f32,f32,f32,f32); {len(walls)}] = [\n'
rs+=''.join('  ('+','.join(rf(c) for c in wall)+'),\n' for wall in walls)
rs+='];\n'

(r/'src/world.generated.rs').write_text(rs,encoding='utf8')
print('Generated shared C/Rust collision geometry:',len(w['houses']),'houses,',len(w['trees']),'trees')

# v0.0.9: the extra two maps share the same data for C/Rust-WASM and Three.js.
areas=json.loads((r/'assets/area-maps.json').read_text(encoding='utf8'))
for map_id, definition in enumerate(areas['maps'][1:],start=1):
    suffix=str(map_id)
    def arr(kind,fields):
        shapes=definition.get(kind,[])
        cols=len(fields)
        # Arrays are never zero length in current test maps.
        key=f'AREA_{suffix}_{kind.upper()}'
        global h,rs
        h+=f'#define {key}_COUNT {len(shapes)}\n'
        h+=f'static const float {key.lower()}[{max(1,len(shapes))}][{cols}] = {{\n'
        h+=''.join('  {'+','.join(cf(shape[f]) for f in fields)+'},\n' for shape in shapes)
        if not shapes: h+='  {'+','.join('0.0f' for f in fields)+'},\n'
        h+='};\n'
        rs+=f'const {key}: [(f32,{",".join("f32" for _ in range(cols-1))}); {len(shapes)}] = [\n' if cols>1 else f'const {key}: [f32;{len(shapes)}]=[\n'
        rs+=''.join('  ('+','.join(rf(shape[f]) for f in fields)+'),\n' for shape in shapes)
        rs+='];\n'
    for key in ('minX','maxX','minZ','maxZ'):
        n=f'AREA_{suffix}_{key.upper()}'
        h+=f'#define {n} {cf(definition["bounds"][key])}\n'
        rs+=f'const {n}: f32 = {rf(definition["bounds"][key])};\n'
    if 'river' in definition:
        for n,k in [('RIVER_HALF_WIDTH','halfWidth'),('RIVER_CENTER_Z','bridgeCenterZ'),('BRIDGE_HALF_WIDTH','bridgeHalfWidth'),('BRIDGE_RAIL_HALF_THICKNESS','railHalfThickness')]:
            h+=f'#define AREA_{suffix}_{n} {cf(definition["river"][k])}\n'
            rs+=f'const AREA_{suffix}_{n}: f32 = {rf(definition["river"][k])};\n'
    arr('houses',('x','z','halfX','halfZ'))
    arr('trees',('x','z','radius'))
    arr('rocks',('x','z','radius'))
(r/'src/world.generated.h').write_text(h,encoding='utf8')
(r/'src/world.generated.rs').write_text(rs,encoding='utf8')
print('Generated extra area geometry')
