import assert from 'node:assert/strict';
import {createWorldClock,advanceWorldClock,worldClockPhase,worldClockLabel,seekWorldClock,worldClockSnapshot} from '../src/world-clock.mjs';
const c=createWorldClock();
assert.equal(worldClockLabel(c),'Day 1 · 17:00');
assert.equal(c.minutesPerRealSecond,12);
assert.equal(worldClockPhase(c),'day');
advanceWorldClock(c,5);
assert.equal(worldClockLabel(c),'Day 1 · 18:00');
assert.equal(worldClockPhase(c),'dusk');
seekWorldClock(c,1439);
const event=advanceWorldClock(c,61/12);
assert.equal(event.dayChanged,true);
assert.equal(c.day,2);
assert.equal(worldClockLabel(c),'Day 2 · 01:00');
c.paused=true;
advanceWorldClock(c,240);
assert.equal(worldClockLabel(c),'Day 2 · 01:00');
c.paused=false;c.minutesPerRealSecond=12;advanceWorldClock(c,300);
assert.equal(c.day,4);
assert.equal(worldClockLabel(c),'Day 4 · 13:00');
const saved=worldClockSnapshot(c);
assert.deepEqual(createWorldClock(saved),saved);
assert.equal(createWorldClock({day:'oops',minuteOfDay:NaN,minutesPerRealSecond:0}).day,1);
assert.equal(createWorldClock({minutesPerRealSecond:0}).minutesPerRealSecond,.1);
console.log('world clock: PASS (tick, day rollover, time of day, pause, speed, save/load)');
