import assert from 'node:assert/strict';
import {createSwim2D, underwaterPalette, UNDERWATER_MODE} from '../src/underwater.mjs';

assert.deepEqual(UNDERWATER_MODE, {environmentMode:'underwater',cameraMode:'side',movementMode:'swim2d'});
const swim=createSwim2D({depthMax:10});
swim.step({down:true},.25);
assert(swim.state.depth>0 && swim.state.vy>0);
for(let i=0;i<20;i++)swim.step({down:true},.25);
assert.equal(swim.state.depth,10);
swim.step({up:true},.5);
assert(swim.state.depth<10);
assert(underwaterPalette(240).light<underwaterPalette(0).light);
const normal=createSwim2D({depth:50}),fast=createSwim2D({depth:50,verticalSpeedMultiplier:1.6});
normal.step({down:true},.2);fast.step({down:true},.2);
assert(Math.abs((fast.state.depth-50)/(normal.state.depth-50)-1.6)<1e-9,'vertical movement is 60% faster');
normal.reset(0,50);fast.reset(0,50);normal.step({up:true},.2);fast.step({up:true},.2);
assert(Math.abs((50-fast.state.depth)/(50-normal.state.depth)-1.6)<1e-9,'ascent uses the same multiplier');
const half=createSwim2D(),full=createSwim2D();
half.step({axisX:.5,axisY:0},.1);full.step({axisX:1,axisY:0},.1);
assert(Math.abs(half.state.x/full.state.x-.5)<1e-9,'stick deflection controls acceleration');
const diagonal=createSwim2D();diagonal.step({axisX:1,axisY:1},.1);
assert(Math.abs(Math.hypot(diagonal.state.vx,diagonal.state.vy)-full.state.vx)<1e-9,'diagonal input is normalized');
console.log('PASS: swim2d acceleration, drag, bounds and depth palette');
